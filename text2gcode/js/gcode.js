/**
 * gcode.js — turn cut paths into GCode + a move list for preview/simulation.
 * Exposes global `GCodeGen` (and module.exports for node testing).
 */
(function (root) {
  'use strict';

  const fmt = (n) => {
    const v = Math.round(n * 1000) / 1000;
    return (Object.is(v, -0) ? 0 : v).toFixed(3);
  };

  /**
   * Expand cut paths into a machine move list (including depth passes).
   * paths: [[x,y],...] cut polylines (mm, y-up)
   * settings: { safeZ, cutDepth, passDepth, feedXY, feedPlunge, rapidFeed }
   * returns { moves: [{type:'rapid'|'cut', pts, z, pass}], stats }
   */
  function buildMoves(paths, settings) {
    const safeZ = settings.safeZ;
    const cutDepth = Math.max(0.01, settings.cutDepth);
    const passDepth = Math.max(0.05, settings.passDepth || cutDepth);
    const passes = Math.max(1, Math.ceil(cutDepth / passDepth));

    const moves = [];
    let cutLen = 0;      // per pass
    let rapidLen = 0;
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;

    for (const pts of paths) {
      if (pts.length < 2) continue;
      // rapid to start (positioning move at safe height)
      moves.push({ type: 'rapid', pts: [[pts[0][0], pts[0][1]]], z: safeZ, pass: 0 });
      for (let p = 0; p < passes; p++) {
        const z = -Math.min(cutDepth, passDepth * (p + 1));
        const start = [pts[0][0], pts[0][1]];
        moves.push({ type: 'plunge', pts: [start], z, pass: p });
        moves.push({ type: 'cut', pts, z, pass: p });
        cutLen += polyLen(pts);
      }
      // bounds from cut geometry
      for (const pt of pts) {
        if (pt[0] < minX) minX = pt[0];
        if (pt[0] > maxX) maxX = pt[0];
        if (pt[1] < minY) minY = pt[1];
        if (pt[1] > maxY) maxY = pt[1];
      }
    }

    // total rapid length: origin to each path start + between paths (approx, at safe Z)
    let prev = null;
    for (const m of moves) {
      if (m.type === 'rapid') {
        if (prev) rapidLen += Math.hypot(m.pts[0][0] - prev[0], m.pts[0][1] - prev[1]);
        prev = m.pts[0];
      }
    }
    const plungeCount = moves.filter((m) => m.type === 'plunge').length;
    const estTimeSec =
      (cutLen) / Math.max(1, settings.feedXY) * 60 +                     // cutting (s, incl. passes)
      (rapidLen / Math.max(1, settings.rapidFeed || 3000)) * 60 +        // rapids (s)
      (cutDepth * plungeCount) / Math.max(1, settings.feedPlunge) * 60;  // plunges (s)

    return {
      moves,
      passes,
      stats: {
        bounds: isFinite(minX) ? { minX, minY, maxX, maxY, width: maxX - minX, height: maxY - minY } : null,
        cutLength: cutLen,
        cutLengthTotal: cutLen,
        rapidLength: rapidLen,
        passes,
        paths: paths.length,
        estTimeMin: estTimeSec / 60,
      },
    };
  }

  function polyLen(pts) {
    let len = 0;
    for (let i = 1; i < pts.length; i++) {
      len += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    }
    return len;
  }

  /**
   * Render GCode text.
   * info: { moves, passes, stats, settings, meta: {text, font, mode, tool} }
   *
   * Returns { text, lineMap } — lineMap[i] links gcode line i to the machine
   * move it came from: { move: <index into info.moves>, pt: <point index for
   * cut moves> } or null for comments/setup lines. Used by the UI so clicking
   * a gcode line can highlight the toolpath it creates.
   */
  function generate(info) {
    const s = info.settings;
    const m = info.meta;
    const L = [];
    const lineMap = [];
    const emit = (line, map) => { L.push(line); lineMap.push(map || null); };
    const now = new Date();
    emit('; CNC Text Engraving — generated by Text2GCode');
    emit(`; ${now.toISOString()}`);
    emit(`; Text: ${String(m.text).replace(/\n/g, ' / ').slice(0, 80)}`);
    emit(`; Font: ${m.font} | Mode: ${m.mode}`);
    emit(`; Tool: ${m.toolDiameter}mm ${m.toolType} | Cut depth: ${s.cutDepth}mm in ${info.passes} pass(es)`);
    emit(`; Feed: XY ${s.feedXY}mm/min, plunge ${s.feedPlunge}mm/min | Spindle ${s.spindleRPM}rpm`);
    emit('');
    emit('G90 ; absolute positioning');
    emit('G21 ; units = millimeters');
    emit('G17 ; XY plane');
    emit(`G0 Z${fmt(s.safeZ)} ; lift tool`);
    if (s.spindleRPM > 0) {
      emit(`M3 S${Math.round(s.spindleRPM)} ; spindle on`);
    }
    emit('');

    let lastPass = -1;
    let firstCutInPass = true;
    for (let mi = 0; mi < info.moves.length; mi++) {
      const mv = info.moves[mi];
      if (mv.pass !== lastPass) {
        if (lastPass !== -1) { emit(`G0 Z${fmt(s.safeZ)}`); emit(''); }
        if (mv.type !== 'rapid') emit(`; --- depth pass ${mv.pass + 1} of ${info.passes} (Z ${fmt(mv.z)}) ---`);
        lastPass = mv.pass;
        firstCutInPass = true;
      }
      if (mv.type === 'rapid') {
        emit(`G0 X${fmt(mv.pts[0][0])} Y${fmt(mv.pts[0][1])}`, { move: mi });
      } else if (mv.type === 'plunge') {
        emit(`G1 Z${fmt(mv.z)} F${fmt(s.feedPlunge)}`, { move: mi });
        firstCutInPass = true;
      } else if (mv.type === 'cut') {
        for (let i = firstCutInPass ? 0 : 1; i < mv.pts.length; i++) {
          const p = mv.pts[i];
          const f = firstCutInPass ? ` F${fmt(s.feedXY)}` : '';
          emit(`G1 X${fmt(p[0])} Y${fmt(p[1])}${f}`, { move: mi, pt: i });
          firstCutInPass = false;
        }
        firstCutInPass = false;
      }
    }
    emit('');
    emit(`G0 Z${fmt(s.safeZ)} ; final retract`);
    if (s.spindleRPM > 0) emit('M5 ; spindle off');
    if (s.returnHome) emit('G0 X0 Y0 ; return to origin');
    emit('M2 ; program end');
    return { text: L.join('\n') + '\n', lineMap };
  }

  const api = { buildMoves, generate, fmt };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.GCodeGen = api;
})(typeof window !== 'undefined' ? window : (typeof global !== 'undefined' ? global : this));